#!/usr/bin/env python3
"""Extract changed documentation Swift fences into the public Consumer without rewriting bodies.

Migration fences are concatenated at file scope. README/security-guide fences are
wrapped in separate async-throwing functions to scope placeholder names and allow
await; import lines are moved to the common header. README cache fence 19 receives
an otherwise empty DynamicPipeline for its pre-existing `pipeline` placeholder.
Nothing in the extracted examples is executed by importing the compiled file.
"""
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[5]
EXECUTION = ROOT / 'docs/superpowers/execution/2026-10-29-pipelinekit-stabilization'
BASELINE = 'a93a713d937e25f68855f22b0720f33c93329b09'
FENCE = re.compile(r'```swift\n(.*?)```', re.S)
FILES = ['docs/migrations/first-stabilization-batch.md', 'README.md',
         'docs/guides/security-best-practices.md', 'docs/guides/resilience-patterns.md']
header = '// Generated by repros/i01_compile_examples.py; edit the source documentation.\n'
header += 'import Foundation\nimport PipelineKit\nimport PipelineKitSecurity\nimport PipelineKitCache\nimport PipelineKitResilience\nimport PipelineKitObservability\n\n'
parts = [header]
manifest = []
for file in FILES:
    body = (ROOT / file).read_text()
    all_fences = FENCE.findall(body)
    old = subprocess.run(['git', 'show', f'{BASELINE}:{file}'], cwd=ROOT,
                         text=True, capture_output=True)
    old_fences = FENCE.findall(old.stdout) if old.returncode == 0 else []
    for number, snippet in enumerate(all_fences, 1):
        if file != FILES[0] and snippet in old_fences:
            continue
        harness = 'exact fence at file scope'
        prefix = f'// {file}, Swift fence {number}\n'
        generated = snippet
        if file != FILES[0]:
            generated = re.sub(r'^import [^\n]+\n', '', snippet, flags=re.M)
            support = ''
            if file == 'README.md' and number == 19:
                support = '    let pipeline = DynamicPipeline()\n'
            name = re.sub('[^a-zA-Z0-9]', '_', file)
            generated = f'@MainActor func compiled_{name}_{number}() async throws {{\n' + support + generated + '\n}\n'
            harness = 'imports hoisted; exact remaining body inside separate @MainActor async throws function'
            if support:
                harness += '; empty DynamicPipeline supplies pipeline placeholder'
        parts.append(prefix + generated + '\n')
        manifest.append(dict(file=file, swift_fence=number,
            snippet_sha256=hashlib.sha256(snippet.encode()).hexdigest(), harness=harness,
            conditional_platform='canImport(Compression)' if '#if canImport(Compression)' in snippet else None))
output = EXECUTION / 'Consumer/Sources/Consumer/CompiledExamples.swift'
output.write_text(''.join(parts))
record = dict(baseline=BASELINE, source='exact current documentation Swift fences',
              generated_file=str(output.relative_to(ROOT)),
              generated_sha256=hashlib.sha256(output.read_bytes()).hexdigest(), snippets=manifest)
(EXECUTION / 'reports/I01-example-manifest.json').write_text(json.dumps(record, indent=2)+'\n')
print(json.dumps(dict(snippets=len(manifest), output=str(output.relative_to(ROOT)))))
